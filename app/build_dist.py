"""Build the standalone StroopMaps window with PyInstaller.

    python app/build_dist.py [--clean]

Output: work/build/dist/StroopMaps/StroopMaps.exe (windowed), a folder rather than one file. Blender is not bundled:
textured maps run the Blender 5.2 installed on the machine (the window has a "Choose blender.exe" button and
remembers the path).

What goes in: the window (backend, fakes, gui), Pillow and numpy, the map modules (MODULES), whatever sm64io.bundle()
adds, and the data files: blender_render.py (run by Blender itself) and stroop_patch/.

Smoke test on the built exe: `StroopMaps.exe --check FILE` must write the JSON of which modules are real or fake.
"""
import json
import os
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
SM = os.path.dirname(HERE)                                      # the folder with the map modules
WORK = os.path.join(SM, 'work', 'build')
DIST_DIR = os.path.join(WORK, 'dist')
NAME = 'StroopMaps'
# the map modules (blender_render.py is Blender's own script, a data file)
MODULES = ['exporter', 'stroopmap', 'sources', 'romload', 'romcol', 'geodecode', 'geolayout', 'render_textured',
           'stroop_install', 'sm64io']
DATA_SM = ['blender_render.py']
# stroop_patch/: the patch, its README and the built dll (bin/); not its work/ (a STROOP clone and build output)
DATA_PATCH = ['hack-maps-0.9.2.patch', 'README.md', 'build.py', 'bin']
EXCLUDES = ['matplotlib', 'scipy', 'pandas', 'IPython', 'pytest', 'setuptools', 'pkg_resources', 'unittest', 'pydoc',
            'doctest', 'numpy.f2py']
HIDDEN = ['tkinter', 'tkinter.ttk', 'tkinter.filedialog', 'tkinter.messagebox', 'numpy', 'PIL', 'PIL.Image',
          'PIL.ImageTk', 'PIL.ImageDraw', 'PIL.ImageGrab', 'PIL.ImageFont', 'selftest', 'ctypes.wintypes', 'json',
          'tomllib', 'xml.etree.ElementTree']

SPEC = '''# generated by app/build_dist.py
a = Analysis([{main!r}], pathex={pathex!r}, binaries=[], datas={datas!r}, hiddenimports={hidden!r}, hookspath=[],
             runtime_hooks=[], excludes={excludes!r}, noarchive=False)
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name={name!r}, console=False, upx=False, icon={icon!r})
coll = COLLECT(exe, a.binaries, a.datas, strip=False, upx=False, name={name!r})
'''


def make_icon(path):
    """Draw the window icon (a folded map) and save it as an .ico at `path`."""
    from PIL import Image, ImageDraw
    n = 256
    im = Image.new('RGBA', (n, n), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle((8, 8, 248, 248), 44, fill=(42, 76, 128, 255))
    d.rounded_rectangle((15, 15, 241, 241), 38, fill=(11, 26, 51, 255))
    d.polygon([(48, 70), (110, 52), (150, 78), (208, 60), (208, 186), (150, 204), (110, 178), (48, 196)],
              fill=(61, 127, 214, 255))
    d.line([(110, 52), (110, 178)], fill=(11, 26, 51, 255), width=6)
    d.line([(150, 78), (150, 204)], fill=(11, 26, 51, 255), width=6)
    d.ellipse((120, 108, 140, 128), fill=(110, 231, 160, 255))
    im.save(path, sizes=[(256, 256), (64, 64), (48, 48), (32, 32), (16, 16)])
    return path


def stroopmaps_modules():
    """The map modules present to bundle."""
    return [m for m in MODULES if os.path.isfile(os.path.join(SM, m + '.py'))]


def extras():
    """sm64io.bundle(): what the build needs besides StroopMaps' own modules (nothing in the standalone sm64io)."""
    sys.path.insert(0, SM)
    import sm64io
    return sm64io.bundle()


def datas():
    """The data files to bundle: Blender's script, the patch files and its built dll."""
    out = []
    for f in DATA_SM:
        if os.path.isfile(os.path.join(SM, f)):
            out.append((os.path.join(SM, f), '.'))
    for f in DATA_PATCH:
        p = os.path.join(SM, 'stroop_patch', f)
        if os.path.exists(p):
            out.append((p, 'stroop_patch/bin' if f == 'bin' else 'stroop_patch'))
    return out + extras()['datas']


def git(*a):
    """A git command's output in this folder, or '' (no git, not a clone)."""
    try:
        r = subprocess.run(['git', '-C', SM] + list(a), capture_output=True, text=True)
        return r.stdout.strip() if r.returncode == 0 else ''
    except OSError:
        return ''


def main():
    """Build, smoke-test and put the exe folder in place."""
    clean = '--clean' in sys.argv
    work = os.path.join(WORK, '_build')
    stage = os.path.join(WORK, '_stage')
    for d in (stage,) + ((work,) if clean else ()):
        shutil.rmtree(d, ignore_errors=True)
    os.makedirs(work, exist_ok=True)
    os.makedirs(DIST_DIR, exist_ok=True)
    gui_mods = ['gui'] + sorted(f'gui.{f[:-3]}' for f in os.listdir(os.path.join(HERE, 'gui'))
                                if f.endswith('.py') and f != '__init__.py')
    sm_mods = stroopmaps_modules()
    ext = extras()
    hidden = HIDDEN + ['backend', 'fakes'] + gui_mods + sm_mods + ext['modules']
    spec = os.path.join(work, NAME + '.spec')
    with open(spec, 'w', encoding='utf-8', newline='\n') as f:
        f.write(SPEC.format(main=os.path.join(HERE, 'main.py'), pathex=[HERE, SM] + ext['paths'], datas=datas(), hidden=hidden,
                            excludes=EXCLUDES, name=NAME, icon=make_icon(os.path.join(work, NAME + '.ico'))))
    print('stroopmaps modules bundled:', ', '.join(sm_mods) or '(none)', flush=True)
    t0 = time.time()
    r = subprocess.run([sys.executable, '-m', 'PyInstaller', '--noconfirm', '--distpath', stage, '--workpath',
                        os.path.join(work, 'pi'), spec], capture_output=True, text=True)
    if r.returncode != 0:
        print((r.stdout + r.stderr)[-3000:])
        raise SystemExit('PyInstaller failed')
    built = os.path.join(stage, NAME)
    for src, rel in ext['beside']:
        os.makedirs(os.path.dirname(os.path.join(built, rel)), exist_ok=True)
        shutil.copyfile(src, os.path.join(built, rel))
    exe = os.path.join(built, NAME + '.exe')
    # smoke test: the packaged exe imports its modules and says which backend modules are real
    out = os.path.join(work, 'check.json')
    if os.path.exists(out):
        os.remove(out)
    try:
        subprocess.run([exe, '--check', out], timeout=90, capture_output=True)
    except subprocess.TimeoutExpired:
        raise SystemExit('smoke test: the exe did not finish in 90 s')
    if not os.path.isfile(out):
        raise SystemExit('smoke test failed: the exe wrote no check file (a module is missing from the bundle?)')
    with open(out, encoding='utf-8') as f:
        chk = json.load(f)
    print('smoke test:', json.dumps(chk), flush=True)
    sys.path.insert(0, HERE)
    import backend
    info = {'version': backend.VERSION, 'built': time.strftime('%Y-%m-%d %H:%M:%S'),
            'commit': git('rev-parse', '--short', 'HEAD'),
            'modules': chk['mode'], 'stroopmaps_modules': sm_mods}
    for name, text in ext.get('files', []):                 # sm64io's own extras (an example config)
        with open(os.path.join(built, name), 'w', encoding='utf-8') as f:
            f.write(text)
    with open(os.path.join(built, 'build_info.json'), 'w', encoding='utf-8') as f:
        json.dump(info, f, indent=1)
    final = os.path.join(DIST_DIR, NAME)
    if os.path.isdir(final):
        try:
            os.replace(final, final + '.probe')       # fails while the exe runs: then the new build goes beside it
            os.replace(final + '.probe', final)
            shutil.rmtree(final)
        except OSError:
            final += '-new'
            shutil.rmtree(final, ignore_errors=True)
    os.replace(built, final)
    size = sum(os.path.getsize(os.path.join(dp, f)) for dp, _d, fs in os.walk(final) for f in fs) / 1e6
    print(f'built {final} ({size:.0f} MB) in {time.time() - t0:.0f} s')


if __name__ == '__main__':
    main()
